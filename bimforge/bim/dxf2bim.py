"""DXF -> IFC: measure directly off 2D CAD plans and author them as BIM.

Pipeline:  DXF --(ezdxf)--> features --(shapely)--> clean geometry
                --(IfcOpenShell)--> IFC4X3 model with typed elements,
                base quantities (Qto), classification/cost codes, and
                optional georeferencing so the model round-trips to KML/GIS.

The moving part you extend is the layer map (see
`bimforge/bim/examples/layer_map.example.yaml`). Everything
downstream is generic.

Author-side notes:
  * All geometry is authored relative to a project base point (a local
    origin), and the base point is written into IfcMapConversion. This keeps
    coordinates small (good for viewers) while preserving real-world position.
  * Georeferencing follows IFC4 semantics: model space is metres, computed as
    (dxf_coord - base) * unit_to_m with the base subtracted in DXF units
    BEFORE converting; IfcMapConversion carries Eastings/Northings as the base
    in CRS units (the yaml values, unchanged) and Scale = 1/unit_to_m, the
    factor that takes model metres back to CRS units (e.g. 3.280839895 for a
    ft CRS). NOTE: IFCs generated by estimating_tools 0.1.10 carry the old,
    broken georeferencing (base subtracted without unit conversion and
    Scale=1.0) and should be regenerated with this version.
  * Quantities are built explicitly with the correct IFC quantity types
    (IfcQuantityArea/Length/Volume/Count) so they are deterministic across
    IfcOpenShell versions and land in the named slots an estimator expects.
"""
from __future__ import annotations

import os
import sys
from dataclasses import dataclass
from typing import Optional

import ezdxf
from shapely.geometry import LineString, Polygon
from shapely.geometry.polygon import orient

import ifcopenshell
from ifcopenshell.api import run

from bimforge.bim.georef import resolve_epsg

# ----------------------------------------------------------------------------
# Units
# ----------------------------------------------------------------------------
UNIT_TO_M = {"mm": 0.001, "cm": 0.01, "m": 1.0, "ft": 0.3048, "in": 0.0254}


# ----------------------------------------------------------------------------
# Feature model  (one measured thing off the plans)
# ----------------------------------------------------------------------------
@dataclass
class Feature:
    layer: str
    ifc_class: str
    predefined_type: Optional[str]
    kind: str                       # "area" | "linear" | "count"
    polygon: Polygon                # footprint in METERS, world coords
    height: float                   # extrusion height (m)
    base_elevation: float           # z of the underside (m)
    measures: dict[str, float]      # quantity name -> value
    classification: Optional[dict]  # {system, code, name}
    properties: dict                # {PsetName: {prop: value}}
    name: str


# ----------------------------------------------------------------------------
# 1. EXTRACT  (ezdxf + shapely)
# ----------------------------------------------------------------------------
def _coords_of(entity, scale: float) -> Optional[list[tuple[float, float]]]:
    """Return a list of (x, y) in meters for a polyline-like entity, else None."""
    t = entity.dxftype()
    pts: list[tuple[float, float]] = []
    if t == "LWPOLYLINE":
        pts = [(p[0] * scale, p[1] * scale) for p in entity.get_points("xy")]
    elif t == "POLYLINE":
        pts = [(v.dxf.location.x * scale, v.dxf.location.y * scale) for v in entity.vertices]
    elif t == "LINE":
        s, e = entity.dxf.start, entity.dxf.end
        pts = [(s.x * scale, s.y * scale), (e.x * scale, e.y * scale)]
    elif t == "HATCH":
        for path in entity.paths:
            if hasattr(path, "vertices"):  # PolylinePath
                pts = [(v[0] * scale, v[1] * scale) for v in path.vertices]
                break
    return pts or None


def extract_features(dxf_path: str, layers_cfg: dict, scale: float) -> list[Feature]:
    doc = ezdxf.readfile(dxf_path)
    msp = doc.modelspace()
    # Case-insensitive layer lookup
    rules = {k.upper(): v for k, v in layers_cfg.items()}
    features: list[Feature] = []
    skipped: dict[str, int] = {}

    for e in msp:
        rule = rules.get(str(e.dxf.layer).upper())
        if not rule:
            continue
        kind = rule.get("feature", "area")
        height = float(rule.get("height", 1.0))
        base_elev = float(rule.get("base_elevation", 0.0))
        cls = rule.get("classification")
        props = rule.get("properties", {}) or {}
        el_class = rule.get("ifc_class", "IfcBuildingElementProxy")
        pdt = rule.get("predefined_type")

        try:
            if kind == "count":
                if e.dxftype() != "INSERT":
                    continue
                p = e.dxf.insert
                m = float(rule.get("marker_size", 0.3))
                cx, cy = p.x * scale, p.y * scale
                poly = Polygon([(cx - m/2, cy - m/2), (cx + m/2, cy - m/2),
                                (cx + m/2, cy + m/2), (cx - m/2, cy + m/2)])
                features.append(Feature(
                    e.dxf.layer, el_class, pdt, "count", poly, height, base_elev,
                    {"Count": 1.0}, cls, {**props, "_Block": {"Name": e.dxf.name}}, e.dxf.name))
                continue

            coords = _coords_of(e, scale)
            if not coords or len(coords) < 2:
                skipped[e.dxftype()] = skipped.get(e.dxftype(), 0) + 1
                continue

            if kind == "linear":
                line = LineString(coords)
                width = float(rule.get("width", 0.2))
                ribbon = line.buffer(width / 2.0, cap_style=2, join_style=2)
                if ribbon.geom_type != "Polygon":
                    ribbon = ribbon.convex_hull
                measures = {
                    "Length": line.length,
                    "Width": width,
                    "Height": height,
                    "GrossVolume": line.length * width * height,
                }
                features.append(Feature(
                    e.dxf.layer, el_class, pdt, "linear", orient(ribbon), height,
                    base_elev, measures, cls, props, f"{e.dxf.layer}-{e.dxf.handle}"))
            else:  # area
                ring = coords if coords[0] == coords[-1] else coords + [coords[0]]
                if len(ring) < 4:
                    skipped[e.dxftype()] = skipped.get(e.dxftype(), 0) + 1
                    continue
                poly = orient(Polygon(ring))
                if not poly.is_valid:
                    poly = poly.buffer(0)
                if poly.is_empty or poly.geom_type != "Polygon":
                    skipped[e.dxftype()] = skipped.get(e.dxftype(), 0) + 1
                    continue
                measures = {
                    "GrossArea": poly.area,
                    "Perimeter": poly.length,
                    "Width": height,          # thickness of a slab-like element
                    "GrossVolume": poly.area * height,
                }
                features.append(Feature(
                    e.dxf.layer, el_class, pdt, "area", poly, height, base_elev,
                    measures, cls, props, f"{e.dxf.layer}-{e.dxf.handle}"))
        except Exception as ex:  # keep going; report at the end
            skipped[f"{e.dxftype()} ({ex})"] = skipped.get(f"{e.dxftype()} ({ex})", 0) + 1

    if skipped:
        for k, n in skipped.items():
            print(f"  [skip] {n}x {k}", file=sys.stderr)
    return features


# ----------------------------------------------------------------------------
# 2. AUTHOR  (IfcOpenShell)
# ----------------------------------------------------------------------------
_QTY_ENTITY = {
    "GrossArea": ("IfcQuantityArea", "AreaValue"),
    "NetArea": ("IfcQuantityArea", "AreaValue"),
    "Perimeter": ("IfcQuantityLength", "LengthValue"),
    "Length": ("IfcQuantityLength", "LengthValue"),
    "Width": ("IfcQuantityLength", "LengthValue"),
    "Height": ("IfcQuantityLength", "LengthValue"),
    "GrossVolume": ("IfcQuantityVolume", "VolumeValue"),
    "NetVolume": ("IfcQuantityVolume", "VolumeValue"),
    "Count": ("IfcQuantityCount", "CountValue"),
}


def _add_quantities(model, element, set_name: str, measures: dict[str, float]):
    """Create an IfcElementQuantity with explicitly-typed quantities."""
    qto = run("pset.add_qto", model, product=element, name=set_name)
    quantities = []
    for qname, value in measures.items():
        ent, attr = _QTY_ENTITY.get(qname, ("IfcQuantityLength", "LengthValue"))
        q = model.create_entity(ent, Name=qname)
        # IfcCountMeasure is an INTEGER in IFC4X3 (a NUMBER in IFC4), and
        # ifcopenshell refuses a float for it.
        if attr == "CountValue" and model.schema_identifier.startswith("IFC4X3"):
            setattr(q, attr, int(round(value)))
        else:
            setattr(q, attr, float(value))
        quantities.append(q)
    qto.Quantities = tuple(quantities)


def _add_classification(model, element, cache: dict, cls: dict):
    """Attach a classification/cost-code reference (Uniclass, MasterFormat, own codes)."""
    system = cls.get("system", "Custom")
    if system not in cache:
        cache[system] = run("classification.add_classification", model, classification=system)
    run("classification.add_reference", model, products=[element],
        identification=str(cls.get("code", "")), name=cls.get("name", ""),
        classification=cache[system])


def build_ifc(features: list[Feature], config: dict, out_path: str) -> str:
    proj_cfg = config.get("project", {})
    schema = proj_cfg.get("schema", "IFC4X3_ADD2")   # #332; "IFC4" opts out
    geo = config.get("georeference", {}) or {}
    unit = (config.get("units", {}) or {}).get("dxf_length_unit", "mm")
    unit_to_m = UNIT_TO_M.get(unit)
    if unit_to_m is None:
        raise ValueError(f"unknown dxf_length_unit '{unit}' (use one of {list(UNIT_TO_M)})")

    model = run("project.create_file", version=schema)
    project = run("root.create_entity", model, ifc_class="IfcProject",
                  name=proj_cfg.get("name", "DXF Takeoff"))
    # SI metres, explicitly: assign_unit's no-arg default is MILLImetres, which
    # would scale stored geometry x1000 and silently mismatch the metre-valued
    # Qto quantities and MapConversion Scale below.
    run("unit.assign_unit", model, units=[
        run("unit.add_si_unit", model, unit_type="LENGTHUNIT"),
        run("unit.add_si_unit", model, unit_type="AREAUNIT"),
        run("unit.add_si_unit", model, unit_type="VOLUMEUNIT"),
    ])

    ctx = run("context.add_context", model, context_type="Model")
    body = run("context.add_context", model, context_type="Model",
               context_identifier="Body", target_view="MODEL_VIEW", parent=ctx)

    site = run("root.create_entity", model, ifc_class="IfcSite", name="Site")
    building = run("root.create_entity", model, ifc_class="IfcBuilding", name="Building")
    storey = run("root.create_entity", model, ifc_class="IfcBuildingStorey",
                 name=proj_cfg.get("storey", "Level 0"))
    run("aggregate.assign_object", model, products=[site], relating_object=project)
    run("aggregate.assign_object", model, products=[building], relating_object=site)
    run("aggregate.assign_object", model, products=[storey], relating_object=building)

    # --- base point (local origin), held in DXF/CRS units -------------------
    # The yaml base (and the projected CRS) are in the DXF's native unit
    # (e.g. ftUS); feature polygons are already in metres. Model space is
    # (dxf_coord - base) * unit_to_m — the base is subtracted in DXF units
    # BEFORE converting, never mixed across unit systems.
    if geo.get("base_easting") is not None and geo.get("base_northing") is not None:
        base_x, base_y = float(geo["base_easting"]), float(geo["base_northing"])
    elif features:
        minx = min(f.polygon.bounds[0] for f in features)
        miny = min(f.polygon.bounds[1] for f in features)
        base_x, base_y = minx / unit_to_m, miny / unit_to_m  # bbox min, DXF units
    else:
        base_x = base_y = 0.0
    base_x_m, base_y_m = base_x * unit_to_m, base_y * unit_to_m

    # --- georeferencing (so it round-trips to KML/GIS) ---------------------
    # IfcMapConversion: Eastings/Northings are the base in CRS units (the yaml
    # values pass through unchanged); Scale converts model metres to CRS units
    # (1/unit_to_m, e.g. 3.280839895 for a ft CRS).
    epsg = resolve_epsg(geo)
    if epsg is not None:
        run("georeference.add_georeferencing", model)
        run("georeference.edit_georeferencing", model,
            projected_crs={"Name": f"EPSG:{epsg}"},
            coordinate_operation={
                "Eastings": base_x, "Northings": base_y,
                "OrthogonalHeight": float(geo.get("base_height", 0.0)),
                "Scale": 1.0 / unit_to_m,
            })

        # See author/emit_ifc.py: convergence-derived TrueNorth on the model
        # context; model axes are grid axes, so MapConversion stays unrotated.
        from bimforge.cad.geo import convergence_deg, true_north_direction
        tnx, tny = true_north_direction(epsg, base_x, base_y)
        ctx.TrueNorth = model.create_entity(
            "IfcDirection", DirectionRatios=(round(tnx, 9), round(tny, 9)))
        print(f"true north ({tnx:+.6f}, {tny:+.6f}) — grid convergence "
              f"{convergence_deg(epsg, base_x, base_y):+.3f} deg at base point",
              file=sys.stderr)

    cls_cache: dict = {}
    made = 0
    for f in features:
        element = run("root.create_entity", model, ifc_class=f.ifc_class,
                      predefined_type=f.predefined_type, name=f.name)
        run("spatial.assign_container", model, products=[element], relating_structure=storey)

        # geometry: profile (relative to the base point, metres) extruded by height
        ring = [(x - base_x_m, y - base_y_m) for x, y in f.polygon.exterior.coords]
        profile = run("profile.add_arbitrary_profile", model, profile=ring)
        rep = run("geometry.add_profile_representation", model, context=body,
                  profile=profile, depth=f.height)
        run("geometry.assign_representation", model, product=element, representation=rep)

        # IfcProduct.PlacementForShapeRepresentation (express rule): a product
        # with a shape representation requires an ObjectPlacement, even when
        # there's no elevation offset -- always assign one (identity when
        # base_elevation is 0/falsy; no matrix arg on edit_object_placement
        # defaults to np.eye(4), i.e. identity).
        if f.base_elevation:
            import numpy as np
            mtx = np.eye(4); mtx[2, 3] = f.base_elevation
            run("geometry.edit_object_placement", model, product=element, matrix=mtx)
        else:
            run("geometry.edit_object_placement", model, product=element)

        # quantities
        qto_name = {"IfcSlab": "Qto_SlabBaseQuantities",
                    "IfcWall": "Qto_WallBaseQuantities"}.get(f.ifc_class,
                    "Qto_TakeoffBaseQuantities")
        _add_quantities(model, element, qto_name, f.measures)

        # classification / cost code
        if f.classification:
            _add_classification(model, element, cls_cache, f.classification)

        # custom property sets
        for pset_name, props in f.properties.items():
            pset = run("pset.add_pset", model, product=element, name=pset_name)
            run("pset.edit_pset", model, pset=pset, properties=props)

        made += 1

    # Name the STEP header after the artifact rather than ifcopenshell's
    # '/dev/null' default — some IFC consumers surface FILE_NAME in metadata
    # and a bogus path reads as ambiguous (or an invalid path).
    try:
        model.header.file_name.name = os.path.basename(out_path)
    except (AttributeError, TypeError):
        pass

    model.write(out_path)
    return f"{made} elements written to {out_path}"
