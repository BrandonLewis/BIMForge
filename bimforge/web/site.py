"""Write and serve the BIMForge web pages for one bundle.

A site is a directory::

    index.html  takeoff.html  dashboard.html
    assets/     app.css  shared.js  takeoff.js  dashboard.js
    data/       bundle.json  bundle.js

`bundle.js` is the bundle assigned to `window.BIMFORGE_BUNDLE`: a page
loads it with a script tag, so the site works opened straight from disk
(a `file://` page cannot fetch a sibling JSON) as well as from a server.
`bundle.json` is the same document for any other consumer.

`serve_site` runs the standard-library HTTP server on the directory: for a
look on one machine, not for production. Put the directory behind any
static web server for a team.
"""
from __future__ import annotations

import shutil
from pathlib import Path

from bimforge.web.contract import dump_bundle, validate_bundle

STATIC = Path(__file__).with_name("static")
PAGES = ("index.html", "takeoff.html", "dashboard.html")


def write_site(bundle: dict, out_dir) -> Path:
    """Write the pages and the bundle into `out_dir`; returns the index."""
    validate_bundle(bundle)
    out = Path(out_dir)
    (out / "assets").mkdir(parents=True, exist_ok=True)
    (out / "data").mkdir(parents=True, exist_ok=True)
    for page in PAGES:
        shutil.copyfile(STATIC / page, out / page)
    for asset in sorted((STATIC / "assets").iterdir()):
        if asset.is_file():
            shutil.copyfile(asset, out / "assets" / asset.name)
    text = dump_bundle(bundle)
    (out / "data" / "bundle.json").write_text(text + "\n", encoding="utf-8")
    (out / "data" / "bundle.js").write_text(
        "// generated by bimforge: the bundle behind the pages\n"
        "window.BIMFORGE_BUNDLE = " + text + ";\n", encoding="utf-8")
    return out / "index.html"


def serve_site(out_dir, port: int = 8765, open_browser: bool = False,
               bind: str = "127.0.0.1") -> None:
    """Serve `out_dir` until interrupted (Ctrl-C)."""
    import functools
    import webbrowser
    from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer

    handler = functools.partial(SimpleHTTPRequestHandler, directory=str(out_dir))
    with ThreadingHTTPServer((bind, port), handler) as httpd:
        url = f"http://{bind}:{httpd.server_address[1]}/"
        print(f"serving {out_dir} at {url} (Ctrl-C to stop)")
        if open_browser:
            webbrowser.open(url)
        try:
            httpd.serve_forever()
        except KeyboardInterrupt:
            pass
